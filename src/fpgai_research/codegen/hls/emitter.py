"""Generate self-contained, static-shape Vitis HLS C++ from Lowered Model IR.

FPGAI_HOST_FLOAT is a useful *non-bit-exact* C++ smoke-test mode; vendor C
simulation and synthesis remain necessary before numerical/HLS QoR claims.
"""
from __future__ import annotations
from dataclasses import dataclass
from hashlib import sha256
from math import prod
import json
import re
from fpgai_research.model_ir.contracts import LoweredModel
from fpgai_research.model_ir.semantics import verify_refinement, functional_fingerprint


@dataclass(frozen=True)
class Emission:
    cpp: str
    manifest: dict


# The legacy V1 generator remains available solely for exact regeneration
# of already archived scientific IR/HLS source receipts. Never silently
# reinterpret an old emission under the current loop compiler.
LOOP_CODEGEN_STATIC="static-trip-v2"
LOOP_CODEGEN_LEGACY="legacy-v1"
LOOP_CODEGEN_CONV_STATIC="static-conv-trip-v3"
LOOP_CODEGEN_VERSIONS=(LOOP_CODEGEN_LEGACY,LOOP_CODEGEN_STATIC,LOOP_CODEGEN_CONV_STATIC)


def emit_hls(model: LoweredModel, *, loop_codegen=None, tensor_layouts=None,
             trace_conv_access: bool=False) -> Emission:
    if type(trace_conv_access) is not bool:
        raise ValueError("Boolean opt-in Conv trace required")
    if trace_conv_access and tensor_layouts:
        raise ValueError("Conv source trace cannot assert unknown physical tensor layouts")
    # The default is operator-aware: preserve complete MatMul v2 evidence,
    # while new Conv cases use the separately versioned bounded-loop source.
    if loop_codegen is None:
        loop_codegen=(LOOP_CODEGEN_CONV_STATIC if any(
            op.kind=="Conv" for op in model.architectural.functional.operators)
            else LOOP_CODEGEN_STATIC)
    if loop_codegen not in LOOP_CODEGEN_VERSIONS:
        raise ValueError("Unsupported explicit HLS loop-codegen version")
    verify_refinement(model)
    # Preserve byte-identical legacy generated source for ordinary calls.
    # Noncanonical intermediate layouts must be checked against compositional
    # IR and realized by *both* producer writes and downstream reads.
    physical_layouts = {}
    if tensor_layouts:
        from fpgai_research.model_ir.composition import resolve_composition
        composed = resolve_composition(model.architectural, layouts=tensor_layouts)
        if composed.lowered != model:
            raise ValueError("Compositional layout disagrees with Lowered IR")
        physical_layouts = composed.layout_by_tensor()
    functional = model.architectural.functional
    functional.validate()
    if len(functional.inputs) != 1 or len(functional.outputs) != 1:
        raise ValueError("Current C++ top supports exactly one input and one output tensor")
    points = {p.operator: p for p in model.architectural.points}
    lowered = {op.name: op for op in model.operators}
    if len(lowered) != len(model.operators) or set(lowered) != set(points):
        raise ValueError("Lowered IR must cover every operator exactly once")
    for name, op in lowered.items():
        if op.architecture != points[name].effective or op.kind != points[name].kind:
            raise ValueError(f"Inconsistent lowered operator: {name}")
    if len({(p.effective.precision_bits, p.effective.integer_bits) for p in points.values()}) != 1:
        raise ValueError("Mixed per-operator numerical formats require explicit cast lowering")
    for op in functional.operators:
        if len(op.outputs) != 1:
            raise ValueError("Only single-output operators are currently supported")
    w, integer = next(iter({(p.effective.precision_bits, p.effective.integer_bits) for p in points.values()}))
    identifiers = {t.name: f"tensor_{i}" for i, t in enumerate(functional.tensors)}
    consts = {t.name for t in functional.tensors if t.data is not None}
    input_name, output_name = functional.inputs[0], functional.outputs[0]
    src = ["// Generated by fpgai_research; architecture requests are E1 intent, not achieved QoR.",
           "#ifdef FPGAI_HOST_FLOAT", "#include <cmath>", "#include <cstdio>", "using data_t = float; // Not bit-exact for ap_fixed", "#else",
           "#include <ap_fixed.h>", "#include <hls_math.h>", f"using data_t = ap_fixed<{w}, {integer}, AP_RND, AP_SAT>;", "#endif", ""]
    for t in functional.tensors:
        if t.name in (input_name, output_name):
            continue
        sym = identifiers[t.name]
        count = prod(t.shape)
        if t.name in consts:
            values = ", ".join(f"data_t({v:.9g})" for v in t.data)
            src.append(f"static const data_t {sym}[{count}] = {{{values}}};")
    src.append(f'extern "C" void fpgai_model(const data_t {identifiers[input_name]}[{prod(functional.tensor(input_name).shape)}], data_t {identifiers[output_name]}[{prod(functional.tensor(output_name).shape)}]) {{')
    for t in functional.tensors:
        if t.name not in (input_name, output_name) and t.name not in consts:
            src.append(f"  data_t {identifiers[t.name]}[{prod(t.shape)}];")
    manifest = {"schema": "fpgai-research/hls-e1/v1",
                "functional_sha256": functional_fingerprint(functional),
                "precision_bits": w, "integer_bits": integer,
                "input_shape": list(functional.tensor(input_name).shape),
                "output_shape": list(functional.tensor(output_name).shape), "operators": []}
    if loop_codegen!=LOOP_CODEGEN_LEGACY:
        manifest["loop_codegen_version"]=loop_codegen
    for ordinal, op in enumerate(functional.operators):
        p = points[op.name]
        lo = lowered[op.name]
        a = lo.architecture
        args = [identifiers[n] for n in op.inputs]
        out = identifiers[op.outputs[0]]
        marker = re.sub(r"[^a-zA-Z0-9_]", "_", op.name)
        if lo.pipeline_ii is not None:
            pragma = f"#pragma HLS PIPELINE II={lo.pipeline_ii}"
        else:
            pragma = ""
        # Restrict untrusted ONNX/YAML labels to single-line C++ comments.
        safe_name = re.sub(r"[^a-zA-Z0-9_.:-]", "_", op.name)
        safe_scope = re.sub(r"[^a-zA-Z0-9_.:-]", "_", p.source_scope)
        src.append(f"  // OP {safe_name}: {op.kind}, scope={safe_scope}, P={lo.replica_count}, PE={lo.pe_count}, SIMD={lo.simd_lanes}, reuse={lo.fold_factor}")
        # The Vitis 2023.2 ap_fixed multiply result is a wider expression
        # type. Mixing it with data_t(0) in ?: is ambiguous and prevents
        # both C simulation and synthesis. Use a typed destination and a
        # guarded assignment so AP_RND/AP_SAT are applied on conversion.
        if op.kind in ("MatMul", "Gemm"):
            m, n, k = lo.iteration_shape
            right_index = f"ni*{k}+kk" if op.kind == "Gemm" and int(op.attr("transB", 0)) else f"kk*{n}+ni"
            tm, tn, tk = lo.tile_shape
            # Explicit physical intermediate array addressing. Arithmetic and
            # logical tensor indices remain unchanged.
            matmul_out_access = (f"{out}[ni*{m}+mi]" if op.outputs[0] in physical_layouts
                                 else f"{out}[mi*{n}+ni]")
            matmul_lhs_access = (f"{args[0]}[kk*{m}+mi]" if op.inputs[0] in physical_layouts
                                 else f"{args[0]}[mi*{k}+kk]")
            pw = lo.replica_count * lo.pe_count
            src += [f"  for (int mb=0; mb<{m}; mb+={tm}) {{",
                    f"    for (int nb=0; nb<{n}; nb+={tn}) {{",
                    f"      for (int ob=0; ob<{tn}; ob+={pw*lo.fold_factor}) {{",
                    f"        for (int fold=0; fold<{lo.fold_factor}; ++fold) {{",
                    f"          for (int replica=0; replica<{lo.replica_count}; ++replica) {{",
                    "#pragma HLS UNROLL",
                    f"            for (int pe=0; pe<{lo.pe_count}; ++pe) {{",
                    "#pragma HLS UNROLL"]
            if loop_codegen==LOOP_CODEGEN_LEGACY:
                src += [
                    f"              const int row_limit = ((mb+{tm})<{m} ? mb+{tm} : {m});",
                    "              for (int mi=mb; mi<row_limit; ++mi) {",
                    f"                int ni=nb+ob+fold*{pw}+replica*{lo.pe_count}+pe;",
                    f"                if (ni >= {n} || ni >= nb+{tn}) continue;",
                    f"                data_t acc = {args[2]}[ni] ;" if len(args) == 3 else "                data_t acc = data_t(0);",
                    f"                for (int kb=0; kb<{k}; kb+={tk}) {{",
                    f"                  for (int ki=kb; ki<{k} && ki<kb+{tk}; ki+={lo.simd_lanes}) {{",
                    pragma,
                    f"                    data_t partial[{lo.simd_lanes}];",
                    "#pragma HLS ARRAY_PARTITION variable=partial complete",
                    f"                    for (int lane=0; lane<{lo.simd_lanes}; ++lane) {{",
                    "#pragma HLS UNROLL",
                    "                      int kk=ki+lane;",
                    "#if defined(FPGAI_HOST_FLOAT) && defined(FPGAI_TRACE_ITERATIONS)",
                    f'                      if(kk<{k} && kk<kb+{tk}) std::printf("FPGAI_ITER {ordinal} %d %d %d %d %d %d %d\\n", mi,ni,kk,replica,pe,lane,fold);',
                    "#endif",
                    "                      partial[lane] = data_t(0);",
                    f"                      if (kk<{k} && kk<kb+{tk}) partial[lane] = {matmul_lhs_access} * {args[1]}[{right_index}];",
                    "                    }",
                    f"                    for (int lane=0; lane<{lo.simd_lanes}; ++lane) acc += partial[lane];",
                    "                  }", "                }",
                    f"                {matmul_out_access} = acc;",
                    "              }", "            }", "          }", "        }", "      }", "    }", "  }"]
            else:
                # Fixed trip counts depend only on shapes and requested tiles.
                # Bounds guards preserve tails without dynamic loop exits.
                # Vitis must still establish native latency/II separately.
                src += [
                    f"              for (int mo=0; mo<{tm}; ++mo) {{",
                    "                const int mi=mb+mo;",
                    f"                const int ni=nb+ob+fold*{pw}+replica*{lo.pe_count}+pe;",
                    f"                if (mi<{m} && ni<{n} && ni<nb+{tn}) {{",
                    f"                  data_t acc = {args[2]}[ni];" if len(args) == 3 else "                  data_t acc = data_t(0);",
                    f"                  for (int kb=0; kb<{k}; kb+={tk}) {{",
                    f"                    for (int ko=0; ko<{tk}; ko+={lo.simd_lanes}) {{",
                    pragma,
                    f"                      data_t partial[{lo.simd_lanes}];",
                    "#pragma HLS ARRAY_PARTITION variable=partial complete",
                    f"                      for (int lane=0; lane<{lo.simd_lanes}; ++lane) {{",
                    "#pragma HLS UNROLL",
                    "                        const int kk=kb+ko+lane;",
                    "#if defined(FPGAI_HOST_FLOAT) && defined(FPGAI_TRACE_ITERATIONS)",
                    f'                        if(kk<{k} && ko+lane<{tk}) std::printf("FPGAI_ITER {ordinal} %d %d %d %d %d %d %d\\n", mi,ni,kk,replica,pe,lane,fold);',
                    "#endif",
                    "                        partial[lane] = data_t(0);",
                    f"                        if (kk<{k} && ko+lane<{tk}) partial[lane] = {matmul_lhs_access} * {args[1]}[{right_index}];",
                    "                      }",
                    f"                      for (int lane=0; lane<{lo.simd_lanes}; ++lane) acc += partial[lane];",
                    "                    }", "                  }",
                    f"                  {matmul_out_access} = acc;",
                    "                }", "              }", "            }", "          }", "        }", "      }", "    }", "  }"]
        elif op.kind == "Conv":
            x, weight = functional.tensor(op.inputs[0]), functional.tensor(op.inputs[1])
            batch, ci, hi, wi = x.shape
            co, _, kh, kw = weight.shape
            _, _, ho, wo = functional.tensor(op.outputs[0]).shape
            strides = tuple(op.attr("strides", (1, 1)))
            pads = tuple(op.attr("pads", (0, 0, 0, 0)))
            _, toc, toh, tow, _, _, _ = lo.tile_shape
            pw = lo.replica_count * lo.pe_count
            if loop_codegen!=LOOP_CODEGEN_CONV_STATIC:
                src += [f"  for(int b=0;b<{batch};++b) {{",
                        f"    for(int cb=0;cb<{co};cb+={toc}) {{",
                        f"      for(int hb=0;hb<{ho};hb+={toh}) {{",
                        f"        for(int wb=0;wb<{wo};wb+={tow}) {{",
                        f"          for(int ob=0;ob<{toc};ob+={pw*lo.fold_factor}) {{",
                        f"            for(int fold=0;fold<{lo.fold_factor};++fold) {{",
                        f"              for(int replica=0;replica<{lo.replica_count};++replica) {{", "#pragma HLS UNROLL",
                        f"                for(int pe=0;pe<{lo.pe_count};++pe) {{", "#pragma HLS UNROLL",
                        f"                  int oc=cb+ob+fold*{pw}+replica*{lo.pe_count}+pe;",
                        f"                  if(oc>={co} || oc>=cb+{toc}) continue;",
                        f"                  for(int oh=hb;oh<{ho} && oh<hb+{toh};++oh) {{",
                        f"                    for(int ow=wb;ow<{wo} && ow<wb+{tow};++ow) {{",
                        f"                      data_t acc={'data_t(0)' if len(args)<3 else args[2]+'[oc]'};",
                        f"                      for(int icb=0;icb<{ci};icb+={lo.simd_lanes}) {{",
                        pragma,
                        f"                        for(int ky=0;ky<{kh};++ky) {{",
                        f"                          for(int kx=0;kx<{kw};++kx) {{",
                        f"                            data_t partial[{lo.simd_lanes}];", "#pragma HLS ARRAY_PARTITION variable=partial complete",
                        f"                            for(int lane=0;lane<{lo.simd_lanes};++lane) {{", "#pragma HLS UNROLL",
                        f"                              int ic=icb+lane, iy=oh*{strides[0]}+ky-{pads[0]}, ix=ow*{strides[1]}+kx-{pads[1]};",
                        "#if defined(FPGAI_HOST_FLOAT) && defined(FPGAI_TRACE_ITERATIONS)",
                        f'                              if(ic<{ci}) std::printf("FPGAI_ITER {ordinal} %d %d %d %d %d %d %d %d %d %d %d\\n", b,oc,oh,ow,ic,ky,kx,replica,pe,lane,fold);',
                        "#endif",
                        "                              partial[lane] = data_t(0);",
                        f"                              if (ic<{ci} && iy>=0 && iy<{hi} && ix>=0 && ix<{wi}) partial[lane] = {args[0]}[((b*{ci}+ic)*{hi}+iy)*{wi}+ix] * {args[1]}[((oc*{ci}+ic)*{kh}+ky)*{kw}+kx];",
                        "                            }",
                        f"                            for(int lane=0;lane<{lo.simd_lanes};++lane) acc+=partial[lane];",
                        "                          }", "                        }", "                      }",
                        f"                      {out}[((b*{co}+oc)*{ho}+oh)*{wo}+ow]=acc;",
                        "                    }", "                  }", "                }", "              }", "            }", "          }", "        }", "      }", "    }", "  }"]
            else:
                # Fixed local output tile trips; old v2 sources remain exact.
                src += [f"  for(int b=0;b<{batch};++b) {{",
                    f"    for(int cb=0;cb<{co};cb+={toc}) {{",
                    f"      for(int hb=0;hb<{ho};hb+={toh}) {{",
                    f"        for(int wb=0;wb<{wo};wb+={tow}) {{",
                    f"          for(int ob=0;ob<{toc};ob+={pw*lo.fold_factor}) {{",
                    f"            for(int fold=0;fold<{lo.fold_factor};++fold) {{",
                    f"              for(int replica=0;replica<{lo.replica_count};++replica) {{", "#pragma HLS UNROLL",
                    f"                for(int pe=0;pe<{lo.pe_count};++pe) {{", "#pragma HLS UNROLL",
                    f"                  const int oc=cb+ob+fold*{pw}+replica*{lo.pe_count}+pe;",
                    f"                  if(oc<{co} && oc<cb+{toc}) {{",
                    f"                    for(int yh=0;yh<{toh};++yh) {{",
                    "                      const int oh=hb+yh;",
                    f"                      if(oh<{ho}) {{",
                    f"                        for(int xw=0;xw<{tow};++xw) {{",
                    "                          const int ow=wb+xw;",
                    f"                          if(ow<{wo}) {{",
                    f"                      data_t acc={'data_t(0)' if len(args)<3 else args[2]+'[oc]'};",
                    f"                      for(int icb=0;icb<{ci};icb+={lo.simd_lanes}) {{",
                    pragma,
                    f"                        for(int ky=0;ky<{kh};++ky) {{",
                    f"                          for(int kx=0;kx<{kw};++kx) {{",
                    f"                            data_t partial[{lo.simd_lanes}];", "#pragma HLS ARRAY_PARTITION variable=partial complete",
                    f"                            for(int lane=0;lane<{lo.simd_lanes};++lane) {{", "#pragma HLS UNROLL",
                    f"                              int ic=icb+lane, iy=oh*{strides[0]}+ky-{pads[0]}, ix=ow*{strides[1]}+kx-{pads[1]};",
                    "#if defined(FPGAI_HOST_FLOAT) && defined(FPGAI_TRACE_ITERATIONS)",
                    f'                              if(ic<{ci}) std::printf("FPGAI_ITER {ordinal} %d %d %d %d %d %d %d %d %d %d %d\\n", b,oc,oh,ow,ic,ky,kx,replica,pe,lane,fold);',
                    "#endif",
                    "                              partial[lane] = data_t(0);",
                    f"                              if (ic<{ci} && iy>=0 && iy<{hi} && ix>=0 && ix<{wi}) partial[lane] = {args[0]}[((b*{ci}+ic)*{hi}+iy)*{wi}+ix] * {args[1]}[((oc*{ci}+ic)*{kh}+ky)*{kw}+kx];",
                    "                            }",
                    f"                            for(int lane=0;lane<{lo.simd_lanes};++lane) acc+=partial[lane];",
                    "                          }", "                        }", "                      }",
                    f"                      {out}[((b*{co}+oc)*{ho}+oh)*{wo}+ow]=acc;",
                    "                          }", "                        }", "                      }", "                    }", "                  }", "                }", "              }", "            }", "          }", "        }", "      }", "    }", "  }"]
            if trace_conv_access and op.inputs[0] not in (input_name,):
                # Source instrument is attached to the SAME array element
                # expression used by a real guarded input load, not a
                # separate event generator. Without this opt-in, generated
                # C++ remains byte-for-byte identical to the baseline.
                source_index=f"((b*{ci}+ic)*{hi}+iy)*{wi}+ix"
                weight_index=f"((oc*{ci}+ic)*{kh}+ky)*{kw}+kx"
                condition=f"ic<{ci} && iy>=0 && iy<{hi} && ix>=0 && ix<{wi}"
                old=f"                              if ({condition}) partial[lane] = {args[0]}[{source_index}] * {args[1]}[{weight_index}];"
                matches=[i for i,line in enumerate(src) if line==old]
                if len(matches)!=1:
                    raise ValueError("Actual Conv source-load instrumentation anchor missing or ambiguous")
                idx=matches[0]
                output_index=f"((b*{co}+oc)*{ho}+oh)*{wo}+ow"
                reduction_index=f"((ic*{kh}+ky)*{kw}+kx)"
                src[idx:idx+1]=[
                    f"                              if ({condition}) {{",
                    f"                                const int __cst_source_index={source_index};",
                    f"                                partial[lane] = {args[0]}[__cst_source_index] * {args[1]}[{weight_index}];",
                    "#if defined(FPGAI_HOST_FLOAT) && defined(FPGAI_TRACE_CONV_SOURCE)",
                    f'                                std::printf("FPGAI_CONV_READ {ordinal} %d %d %d %d %d %d %d\\n",{output_index},__cst_source_index,{reduction_index},replica,pe,lane,fold);',
                    "#endif",
                    "                              }",
                ]
        elif op.kind == "MaxPool":
            a_shape = functional.tensor(op.inputs[0]).shape
            bsz, channels, hi, wi = a_shape
            _, _, ho, wo = functional.tensor(op.outputs[0]).shape
            src += [f"  for(int b=0;b<{bsz};++b) for(int c=0;c<{channels};++c)",
                    f"    for(int y=0;y<{ho};++y) for(int x=0;x<{wo};++x) {{",
                    pragma,
                    f"      data_t mx={args[0]}[((b*{channels}+c)*{hi}+2*y)*{wi}+2*x];",
                    f"      for(int ky=0;ky<2;++ky) for(int kx=0;kx<2;++kx) {{",
                    f"        data_t z={args[0]}[((b*{channels}+c)*{hi}+2*y+ky)*{wi}+2*x+kx];",
                    "        if(z>mx) mx=z;", "      }",
                    f"      {out}[((b*{channels}+c)*{ho}+y)*{wo}+x]=mx;", "    }"]
        elif op.kind == "GlobalAveragePool":
            n, c, h, width = functional.tensor(op.inputs[0]).shape
            src += [f"  for(int b=0;b<{n};++b) for(int ch=0;ch<{c};++ch) {{",
                    "    data_t acc=data_t(0);",
                    f"    for(int i=0;i<{h*width};++i) {{", pragma,
                    f"      acc += {args[0]}[(b*{c}+ch)*{h*width}+i];",
                    "    }",
                    f"    {out}[b*{c}+ch]=acc/data_t({h*width});", "  }"]
        elif op.kind == "Concat":
            out_shape = functional.tensor(op.outputs[0]).shape
            batch = out_shape[0]
            spatial = prod(out_shape[2:])
            offset = 0
            for name in op.inputs:
                channels = functional.tensor(name).shape[1]
                span = channels * spatial
                src += [f"  for(int b=0;b<{batch};++b) for(int i=0;i<{span};++i) {{",
                        pragma,
                        f"    {out}[b*{out_shape[1] * spatial}+{offset}+i]={identifiers[name]}[b*{span}+i];",
                        "  }"]
                offset += span
        elif op.kind == "BatchNormalization":
            batch, channels, height, width = functional.tensor(op.inputs[0]).shape
            eps = float(op.attr("epsilon", 1e-5))
            src += [f"  for(int b=0;b<{batch};++b) for(int c=0;c<{channels};++c) {{",
                    "#ifdef FPGAI_HOST_FLOAT",
                    f"    data_t norm=data_t(1)/std::sqrt({args[4]}[c]+data_t({eps:.12g}));",
                    "#else",
                    f"    data_t norm=data_t(1)/hls::sqrt({args[4]}[c]+data_t({eps:.12g}));",
                    "#endif",
                    f"    for(int i=0;i<{height*width};++i) {{", pragma,
                    f"      const int pos=(b*{channels}+c)*{height*width}+i;",
                    f"      {out}[pos]=({args[0]}[pos]-{args[3]}[c])*norm*{args[1]}[c]+{args[2]}[c];",
                    "    }", "  }"]
        elif op.kind == "Transpose":
            rows, cols = functional.tensor(op.inputs[0]).shape
            src += [f"  for(int i=0;i<{rows};++i) for(int j=0;j<{cols};++j) {{", pragma,
                    f"    {out}[j*{rows}+i]={args[0]}[i*{cols}+j];", "  }"]
        elif op.kind == "Softmax":
            batch, cols = functional.tensor(op.outputs[0]).shape
            src += [f"  for(int row=0;row<{batch};++row) {{",
                    f"    data_t mx={args[0]}[row*{cols}];",
                    f"    for(int col=1;col<{cols};++col) if({args[0]}[row*{cols}+col]>mx) mx={args[0]}[row*{cols}+col];",
                    "    data_t total=0;",
                    f"    for(int col=0;col<{cols};++col) {{", pragma,
                    "#ifdef FPGAI_HOST_FLOAT",
                    f"      data_t e=std::exp({args[0]}[row*{cols}+col]-mx);",
                    "#else",
                    f"      data_t e=hls::exp({args[0]}[row*{cols}+col]-mx);",
                    "#endif",
                    f"      {out}[row*{cols}+col]=e; total+=e;",
                    "    }",
                    f"    for(int col=0;col<{cols};++col) {out}[row*{cols}+col]/=total;",
                    "  }"]
        elif op.kind in ("Relu", "Identity", "Flatten", "Reshape", "Squeeze", "Unsqueeze", "Add", "Mul", "Sigmoid", "LeakyRelu"):
            count = prod(functional.tensor(op.outputs[0]).shape)
            src += [f"  for(int i=0;i<{count};++i) {{", pragma]
            if op.kind == "Relu":
                src.append(f"    {out}[i] = {args[0]}[i]>data_t(0) ? {args[0]}[i] : data_t(0);")
            elif op.kind == "LeakyRelu":
                alpha = float(op.attr("alpha", 0.01))
                src += [f"    if ({args[0]}[i] >= data_t(0)) {out}[i] = {args[0]}[i];",
                        f"    else {out}[i] = data_t({alpha:.12g}) * {args[0]}[i];"]
            elif op.kind in ("Add", "Mul"):
                from fpgai_research.frontend.broadcast import broadcast_flat_index
                output_shape = functional.tensor(op.outputs[0]).shape
                left = broadcast_flat_index(functional.tensor(op.inputs[0]).shape, output_shape)
                right = broadcast_flat_index(functional.tensor(op.inputs[1]).shape, output_shape)
                arithmetic = '+' if op.kind == 'Add' else '*'
                src.append(f"    {out}[i] = {args[0]}[{left}]{arithmetic}{args[1]}[{right}];")
            elif op.kind == "Sigmoid":
                src += ["#ifdef FPGAI_HOST_FLOAT",
                        f"    {out}[i]=data_t(1)/(data_t(1)+std::exp(-{args[0]}[i]));",
                        "#else",
                        f"    {out}[i]=data_t(1)/(data_t(1)+hls::exp(-{args[0]}[i]));",
                        "#endif"]
            else:
                src.append(f"    {out}[i] = {args[0]}[i];")
            src.append("  }")
        else:
            raise ValueError(f"Missing HLS materialization for {op.kind}")
        # GCC-only introspection of every materialized Functional Model IR
        # tensor boundary. This is never emitted as active Vitis code.
        trace_elements = prod(functional.tensor(op.outputs[0]).shape)
        trace_access = f"{out}[__trace_i]"
        if op.outputs[0] in physical_layouts:
            trace_rows, trace_cols = functional.tensor(op.outputs[0]).shape
            trace_access = f"{out}[(__trace_i%{trace_cols})*{trace_rows}+(__trace_i/{trace_cols})]"
        src += ["#if defined(FPGAI_HOST_FLOAT) && defined(FPGAI_TRACE_TENSORS)",
                f"  for(int __trace_i=0;__trace_i<{trace_elements};++__trace_i) {{",
                f'    std::printf("FPGAI_TENSOR {ordinal} %d %.9g\\n", __trace_i, double({trace_access}));',
                "  }", "#endif"]
        manifest["operators"].append({"operator": op.name, "kind": op.kind,
            "iteration_shape": list(lo.iteration_shape), "source_scope": lo.source_scope,
            "lowered_mechanisms": {"tile_shape": list(lo.tile_shape),
              "replicas": lo.replica_count, "pe_count": lo.pe_count,
              "simd_lanes": lo.simd_lanes, "fold_factor": lo.fold_factor,
              "pipeline_ii": lo.pipeline_ii, "tail_policy": lo.tail_policy,
              "numerical_type": lo.numerical_type},
            "requested": vars(p.requested), "effective": vars(p.effective),
            "decision_sources": dict(lo.decision_sources),
            "evidence": "E1-source-only"})
    src.append("}")
    cpp = "\n".join(line for line in src if line) + "\n"
    if physical_layouts:
        manifest["tensor_physical_layouts"] = dict(sorted(physical_layouts.items()))
        manifest["boundary_evidence"] = "E1-HLS-source-addressing-only"
    if trace_conv_access:
        manifest["conv_source_read_trace_opt_in"]=True
        manifest["evidence_conv_trace"]="GCC-source-read-events-only-no-Vitis-RTL"
    manifest["cpp_sha256"] = sha256(cpp.encode()).hexdigest()
    return Emission(cpp, manifest)
