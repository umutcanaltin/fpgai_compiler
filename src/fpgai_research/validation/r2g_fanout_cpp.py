"""CST R2g original GCC: independently validate dynamic 2..4 fanout source.

Independent raw stdout parser reconstructs typed producer CONTRIBUTE,
COMMIT and consumer READ events plus a numerical value after EVERY
intermediate COMMIT. A distinct mathematical forward Phi issue oracle,
source readiness/alias/reduction oracle and NumPy ALL-INTERMEDIATE
numerical oracle verify the C++ output; the parsed event list is NOT
compared to an event list generated by the C++ emitter.

The source emitter is a distinct runtime-loop implementation, not a
trace-replay template. E1 GCC is NOT HLS hardware-cycle/port evidence.
"""
from __future__ import annotations

from dataclasses import asdict
from hashlib import sha256
from pathlib import Path
from tempfile import TemporaryDirectory
import json
import shutil
import subprocess

import numpy as np

from fpgai_research.codegen.hls.r2g_fanout_cpp import SCHEMA as EMITTER_SCHEMA
from fpgai_research.model_ir.fanout_contract import (
    FanoutEvent,admit_fanout,disjoint_fanout_offsets,
    verify_fanout_events,verify_fanout_issue,
)
from fpgai_research.model_ir.semantics import (
    functional_fingerprint,architecture_fingerprint,
)
from fpgai_research.validation.r2b_interleaved_cpp import _float_literal
from fpgai_research.validation.reference import evaluate

SCHEMA="fpgai-research/cst-R2g-independent-runtime-fanout-GCC-e1/v1"


def decode_stdout(raw:str,*,max_events:int=100_000,
                  max_bytes:int=8*1024*1024):
    if not isinstance(raw,str) or len(raw.encode())>max_bytes:
        raise ValueError("Unbounded/malformed original R2g source stdout")
    events=[]
    values={}
    outputs={}
    expected_value=None
    in_outputs=False
    for line_no,line in enumerate(raw.splitlines(),1):
        fields=line.split()
        if len(fields)<2 or fields[0]!="FPGAI_R2G":
            raise ValueError(f"R2G_INVALID_SOURCE_LOG line={line_no}")
        op=fields[1]
        if expected_value is not None and op!="VALUE":
            raise ValueError(f"R2G_MISSING_ADJACENT_COMMIT_VALUE line={line_no}")
        if op=="CONTRIBUTE":
            if in_outputs or len(fields)!=9:
                raise ValueError("R2G_INVALID_PRODUCER_TERM")
            try:
                event=FanoutEvent("CONTRIBUTE",fields[2],int(fields[3]),
                    fields[4],int(fields[5]),int(fields[6]),
                    int(fields[7]),int(fields[8]))
            except ValueError as exc:
                raise ValueError("R2G_INVALID_PRODUCER_TERM_NUMBER") from exc
            events.append(event)
        elif op=="READ":
            if in_outputs or len(fields)!=10:
                raise ValueError("R2G_INVALID_SOURCE_READ")
            try:
                integers=[int(v) for v in fields[3:4]+fields[5:]]
            except ValueError as exc:
                raise ValueError("R2G_INVALID_SOURCE_READ_NUMBER") from exc
            index=integers[0]
            out=integers[1]
            owner=tuple(integers[2:])
            if len(owner)!=4:
                raise ValueError("R2G_INVALID_SOURCE_OWNER_ARITY")
            events.append(FanoutEvent("READ",fields[2],index,fields[4],
                out,phi_owner=None if owner==(-1,-1,-1,-1) else owner))
        elif op=="COMMIT":
            if in_outputs or len(fields)!=4:
                raise ValueError("R2G_INVALID_SOURCE_COMMIT")
            try:
                idx=int(fields[3])
            except ValueError as exc:
                raise ValueError("R2G_INVALID_SOURCE_COMMIT_INDEX") from exc
            event=FanoutEvent("COMMIT",fields[2],idx)
            events.append(event)
            expected_value=(fields[2],idx)
        elif op=="VALUE":
            if len(fields)!=5 or expected_value is None or in_outputs:
                raise ValueError("R2G_ORPHAN_OR_INVALID_SOURCE_VALUE")
            try:
                idx=int(fields[3])
                value=float(fields[4])
            except ValueError as exc:
                raise ValueError("R2G_INVALID_SOURCE_NUMERIC_VALUE") from exc
            if (not np.isfinite(value) or (fields[2],idx)!=expected_value
                    or expected_value in values):
                raise ValueError("R2G_NONFINITE_OR_UNMATCHED_SOURCE_VALUE")
            values[expected_value]=value
            expected_value=None
        elif op=="OUTPUT":
            if len(fields)!=4:
                raise ValueError("R2G_INVALID_OUTPUT")
            in_outputs=True
            try:
                idx=int(fields[2])
                value=float(fields[3])
            except ValueError as exc:
                raise ValueError("R2G_INVALID_OUTPUT_NUMERIC_VALUE") from exc
            if idx<0 or not np.isfinite(value) or idx in outputs:
                raise ValueError("R2G_DUPLICATE_OR_NONFINITE_OUTPUT")
            outputs[idx]=value
        else:
            raise ValueError("R2G_UNKNOWN_SOURCE_EVENT")
        if len(events)>max_events:
            raise ValueError("R2G_SOURCE_EVENT_BUDGET_EXCEEDED")
    if expected_value is not None:
        raise ValueError("R2G_FINAL_COMMIT_VALUE_MISSING")
    return tuple(events),values,outputs


def verify_fanout_gcc(arch,emission,*,runtime_input,
                      cxx:str="g++",timeout_seconds:int=90,
                      original_trace_output:str|Path|None=None,
                      atol:float=1e-5,rtol:float=1e-4)->dict:
    if type(timeout_seconds) is not int or not 1<=timeout_seconds<=180:
        raise ValueError("R2g bounded GCC tool execution required")
    if original_trace_output is not None:
        path=Path(original_trace_output)
        if path.exists() or path.is_symlink():
            raise FileExistsError("Original R2g GCC evidence must be create-only")
        if not path.parent.is_dir():
            raise ValueError("Original R2g source evidence parent missing")
    compiler=shutil.which(cxx)
    if compiler is None:
        raise FileNotFoundError("Real host g++ compiler required")
    spec=admit_fanout(arch)
    m,k,n,q=spec.m,spec.k,spec.n,spec.q
    model=arch.functional
    manifest=emission.manifest
    source_digest=sha256(emission.cpp.encode()).hexdigest()
    offsets=disjoint_fanout_offsets(spec)
    if (manifest.get("schema")!=EMITTER_SCHEMA
            or manifest.get("source_cpp_sha256")!=source_digest
            or manifest.get("functional_sha256")!=functional_fingerprint(model)
            or manifest.get("architecture_sha256")!=architecture_fingerprint(arch)
            or manifest.get("source_offsets")!=dict(sorted(offsets.items()))
            or manifest.get("fanout")!=len(spec.readers)
            or manifest.get("shape")!=[m,k,n,q]):
        raise ValueError("R2g source/model/Phi/scratch SHA lineage mismatch")
    x=np.asarray(runtime_input,dtype=np.float32)
    if x.shape!=(m,k) or not np.all(np.isfinite(x)):
        raise ValueError("R2g invalid original input matrix")
    # The model interpreter does not depend on the emitted C++ source
    # and returns EACH intermediate, not only final ReLU output.
    numerical=evaluate(model,{spec.input:x},return_all=True)
    input_text=",".join(_float_literal(float(v)) for v in x.flat)
    runner=(
        "\nint main() {\n"
        f"  float input[{m*k}]={{{input_text}}};\n"
        f"  float output[{m*q}]={{}};\n"
        "  fpgai_model(input,output);\n"
        f'  for(int i=0;i<{m*q};++i) '
        'std::printf("FPGAI_R2G OUTPUT %d %.9g\\n",i,double(output[i]));\n'
        "  return 0;\n}\n"
    )
    with TemporaryDirectory(prefix="cst_r2g_original_GCC_") as tmp:
        source=Path(tmp)/"original_r2g.cpp"
        exe=Path(tmp)/"original_r2g"
        source.write_text(emission.cpp+runner)
        compile_result=subprocess.run([
            compiler,"-std=c++17","-O0","-ffp-contract=off",
            "-DFPGAI_HOST_FLOAT","-DFPGAI_TRACE_R2G",
            str(source),"-o",str(exe),
        ],capture_output=True,text=True,timeout=timeout_seconds)
        if compile_result.returncode:
            raise RuntimeError(
                "R2G_ORIGINAL_GCC_COMPILE_FAILED "+
                compile_result.stderr[-4000:])
        run=subprocess.run([str(exe)],capture_output=True,
                           text=True,timeout=timeout_seconds)
        if run.returncode:
            raise RuntimeError(
                "R2G_ORIGINAL_GCC_RUN_FAILED "+run.stderr[-4000:])
    events,values,outputs=decode_stdout(run.stdout)
    source_proof=verify_fanout_events(arch,offsets,events)
    if source_proof["status"]!="VERIFIED_E0":
        raise AssertionError(
            "R2G_RUNTIME_REDUCTION_OR_ALIAS_MISMATCH "+
            str(source_proof))
    issue=verify_fanout_issue(arch,events)
    if issue["status"]!="VERIFIED_E0":
        raise AssertionError(
            "R2G_INDEPENDENT_RUNTIME_PHI_ISSUE_MISMATCH "+
            str(issue))
    expected_values={(tensor,index):float(v)
                     for tensor in spec.intermediates
                     for index,v in enumerate(np.asarray(
                         numerical[tensor],dtype=np.float32).reshape(-1))}
    if set(values)!=set(expected_values):
        raise AssertionError("R2G_INTERMEDIATE_VALUE_POPULATION_MISMATCH")
    errors={}
    for tensor in spec.intermediates:
        actual=np.asarray([
            values[(tensor,i)] for i in range(
                np.asarray(numerical[tensor]).size)],dtype=np.float64)
        wanted=np.asarray(numerical[tensor],
                          dtype=np.float32).reshape(-1).astype(np.float64)
        if not np.allclose(actual,wanted,atol=atol,rtol=rtol):
            raise AssertionError(
                f"R2G_INDEPENDENT_INTERMEDIATE_NUMERIC_MISMATCH tensor={tensor} "+
                str(float(np.max(np.abs(actual-wanted)))))
        errors[tensor]=float(np.max(np.abs(actual-wanted)))
    if set(outputs)!=set(range(m*q)):
        raise AssertionError("R2G_INCOMPLETE_FINAL_OUTPUT")
    out=np.asarray([outputs[i] for i in range(m*q)],dtype=np.float64)
    ref=np.asarray(numerical[model.outputs[0]],dtype=np.float32).reshape(-1)
    if not np.allclose(out,ref,atol=atol,rtol=rtol):
        raise AssertionError("R2G_INDEPENDENT_FINAL_NUMERIC_MISMATCH")
    if original_trace_output is not None:
        with Path(original_trace_output).open("x",encoding="utf-8") as f:
            f.write(run.stdout)
    return {
        "schema":SCHEMA,
        "status":"ORIGINAL_GCC_RUNTIME_2_TO_4_FANOUT_E1_VERIFIED",
        "source_cpp_sha256":source_digest,
        "functional_sha256":manifest["functional_sha256"],
        "architecture_sha256":manifest["architecture_sha256"],
        "original_input_sha256":sha256(x.tobytes()).hexdigest(),
        "original_stdout_sha256":sha256(run.stdout.encode()).hexdigest(),
        "runtime_event_sha256":source_proof["source_event_sha256"],
        "fanout_readers":len(spec.readers),
        "original_producer_contributions":source_proof["producer_contributions"],
        "original_H_reader_reads":source_proof["actual_H_reads"],
        "source_intermediate_values":len(values),
        "source_intermediate_max_absolute_error":max(errors.values()),
        "source_intermediate_max_abs_error_by_tensor":errors,
        "source_final_max_absolute_error":float(np.max(np.abs(out-ref))),
        "original_GCC_compilations":1,"original_GCC_executions":1,
        "original_Vitis_calls":0,"original_Vivado_calls":0,
        "source_runtime_index_generator_event_replay":False,
        "independent_Phi_policy_verification":True,
        "independent_source_alias_and_reduction_verification":True,
        "independent_all_intermediate_numeric_verification":True,
        "hardware_cycle_or_BRAM_savings_proven":False,
        "external_compiler_firstness_proven":False,
        "limitations":[
            "Source events run on a sequential host, not a hardware schedule",
            "Disjoint source scratch layout; the E0 unit-slot optimal mapping is not emitted",
            "Fixed MatMul/left-Add/Relu fanout, not arbitrary operator DAG",
            "No RTL/port/clock/physical BRAM or trained RL evaluation",
        ],
    }
