"""Source-reaudited, privacy-safe E4 paper table from the independent suite.

Formatting never upgrades native observations. Qualified OOC resources and
WNS only; numeric comparisons remain TBD unless BOTH source-attested
physical implementations and the private context matched.
"""
from __future__ import annotations

from math import isfinite

SCHEMA="fpgai-research/independent-matched-e4-audit/v1"
_NAMES={"mnist_cnn":"CNN","mnist_mlp":"MLP"}
_AXES={"baseline":"baseline","parallelism":"replicas","pes":"PEs","simd":"SIMD"}
_RESOURCES=("lut","ff","dsp","bram","uram")


def _num(v):
    return type(v) in (float,int) and isfinite(v)


def render_native_e4_latex(result:dict)->str:
    """Render only qualified and whitelisted numeric publication evidence."""
    if (result.get("schema")!=SCHEMA or result.get("case_count")!=8
            or result.get("vendor_tools_executed_by_audit") is not False
            or result.get("on_device_latency_verified") is not False
            or result.get("private_paths_or_digests_exported") is not False
            or result.get("private_weights_exported") is not False):
        raise ValueError("Not an independently qualified native E4 audit")
    rows=result.get("cases")
    pairs=(result.get("paired_physical_comparisons") or {}).get("pairs")
    if (not isinstance(rows,list) or len(rows)!=8
            or not isinstance(pairs,list) or len(pairs)!=4):
        raise ValueError("Incomplete eight-case E4 provenance or four-pair plan")
    qualified=sum(row.get("qualified_e4") is True for row in rows)
    if qualified!=result.get("e4_qualified_case_count"):
        raise ValueError("Native E4 qualification counter disagrees")
    output=[
        "% Autogenerated by source-attested independent OOC Vivado audit.",
        "% TBD means no qualified native physical observation: never impute E3.",
        r"\begin{table}[t]",r"\centering\scriptsize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{@{}llrrrrrr@{}}",
        r"\toprule",
        r"Model & Axis & WNS (ns) & LUT & FF & DSP & BRAM & URAM \\",
        r"\midrule",
    ]
    seen=set()
    for row in rows:
        model=_NAMES.get(row.get("model"))
        axis=_AXES.get(row.get("axis"))
        key=(row.get("model"),row.get("case"))
        if not model or not axis or key in seen:
            raise ValueError("Unexpected or duplicate private case label")
        seen.add(key)
        if row.get("qualified_e4") is True:
            if (row.get("qualification_status")!="E4_QUALIFIED_MATCHED_OOC"
                    or row.get("implementation_mode")!="out_of_context"
                    or row.get("numerical_csim_passed") is not True
                    or row.get("postroute_timing_met") is not True
                    or row.get("routed_nets_complete") is not True
                    or row.get("drc_summary_verified") is not True
                    or row.get("drc_critical_warnings")!=0
                    or row.get("drc_unconstrained_io") is not False):
                raise ValueError("E4 status/DRC/timing evidence mismatch")
            wns=row.get("postroute_wns_ns")
            resources=row.get("postroute_utilization")
            if (not _num(wns) or wns<0 or not isinstance(resources,dict)
                    or any(not _num(resources.get(k)) or resources[k]<0
                           for k in _RESOURCES)):
                raise ValueError("Missing or invalid native postroute values")
            vals=[f"{wns:.3f}"]+[str(resources[k]) for k in _RESOURCES]
        else:
            vals=["TBD"]*6
        output.append(" & ".join((model,axis,*vals))+r" \\")
    output.extend([
        r"\bottomrule",r"\end{tabular}}",
        r"\caption{Independent source- and RTL-attested out-of-context "
        r"Vivado E4 results (WNS in ns; post-route utilization). "
        r"Unqualified or unexecuted cases are explicitly TBD. "
        r"These results do not measure neural inference latency, "
        r"power, or achieved operator-level II.}",
        r"\label{tab:fpgai-independent-routed-e4}",
        r"\end{table}","",
        r"\begin{table}[t]",r"\centering\scriptsize",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{@{}llllrrr@{}}",
        r"\toprule",
        r"Model & Axis A & Axis B & Status & $\Delta$WNS (ns) & $\Delta$LUT & $\Delta$DSP \\",
        r"\midrule",
    ])
    pair_ids={"cnn_baseline_simd","cnn_parallelism_pes",
              "mlp_parallelism_pes","mlp_baseline_simd"}
    seen_pair=set()
    for pair in pairs:
        model=_NAMES.get(pair.get("model"))
        aa=_AXES.get(pair.get("axis_a"))
        bb=_AXES.get(pair.get("axis_b"))
        ident=pair.get("pair_id")
        if not all((model,aa,bb)) or ident not in pair_ids or ident in seen_pair:
            raise ValueError("Unrecognized or duplicated physical pair")
        seen_pair.add(ident)
        completed=pair.get("status")=="QUALIFIED_MATCHED_PHYSICAL_COMPARISON"
        if completed:
            if (pair.get("both_e4_qualified") is not True
                    or pair.get("matched_physical_context_verified") is not True):
                raise ValueError("Unmatched pair cannot enter paper")
            delta=pair.get("postroute_utilization_delta_b_minus_a")
            wns=pair.get("postroute_wns_delta_b_minus_a_ns")
            if (not isinstance(delta,dict) or not _num(wns)
                    or not _num(delta.get("lut")) or not _num(delta.get("dsp"))):
                raise ValueError("Invalid physical comparison")
            values=[f"{wns:+.3f}",str(delta["lut"]),str(delta["dsp"])]
        else:
            if pair.get("status") not in (
                    "AWAITING_TWO_QUALIFIED_E4_CASES",
                    "MATCHED_CONTEXT_UNVERIFIED_OR_DIFFERENT"):
                raise ValueError("Unknown physical comparison status")
            values=["TBD"]*3
        output.append(" & ".join((model,aa,bb,
                         "matched" if completed else "pending",*values))+r" \\")
    if seen_pair!=pair_ids:
        raise ValueError("Missing preregistered physical comparisons")
    output.extend([
        r"\bottomrule",r"\end{tabular}}",
        r"\caption{Preregistered independent OOC physical comparisons. "
        r"Differences are B minus A. Values appear only when both cases "
        r"qualify and model/target/clock/numeric/tool and synthesis-Tcl "
        r"contexts match. WNS differences are slack differences, "
        r"not inference latency or throughput.}",
        r"\label{tab:fpgai-e4-matched-pairs}",
        r"\end{table}","",
    ])
    # Interpret only independently qualified, same-context physical
    # contrasts. This is observational QoR identity, NEVER equivalence
    # of functionality, circuits, routing or measured inference time.
    completed=[p for p in pairs
               if p["status"]=="QUALIFIED_MATCHED_PHYSICAL_COMPARISON"]
    if completed:
        output.extend([r"\noindent\textbf{Routed physical observations.}"])
    for pair in completed:
        wns=pair["postroute_wns_delta_b_minus_a_ns"]
        delta=pair["postroute_utilization_delta_b_minus_a"]
        if (not _num(wns) or not isinstance(delta,dict)
                or any(not _num(delta.get(resource))
                       for resource in _RESOURCES)):
            raise ValueError("Cannot interpret incomplete native physical difference")
        equal=wns==0 and all(delta[resource]==0 for resource in _RESOURCES)
        model=_NAMES[pair["model"]]
        first=_AXES[pair["axis_a"]]
        second=_AXES[pair["axis_b"]]
        prefix=model+" "+first+" vs. "+second+": "
        if equal:
            interpretation=(
                "the reported post-route WNS and all five utilization "
                "counts coincide under the audited matching constraints. "
                "This is an observational QoR tie, not proof of netlist "
                "identity, formal equivalence or repeated-run invariance.")
        else:
            interpretation=(
                "at least one post-route WNS or utilization observation "
                "differs under the audited matching constraints. "
                "These data alone do not establish its architectural "
                "cause or an application-latency improvement.")
        output.extend([r"\par\noindent "+prefix+interpretation])
    if completed:
        output.append("")
    return "\n".join(output)
